"""Visual pass for LensDirt (halation + dirt) and TapeTear, with Studio unable to render.

The textures are generated by the SAME algorithms and constants as the Luau scripts (ported line for
line), then composited the way the ScreenGuis composite them, over a drawn stand-in of a Backrooms
corridor with ceiling fluorescents at known depths. Three frames: plain, lens (halos + dirt), tear.
"""
import math
import random

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

W, H = 1280, 720
rng = random.Random(7)


# ---------------------------------------------------------------- the stand-in corridor
def corridor():
    im = Image.new("RGB", (W, H), (0, 0, 0))
    d = ImageDraw.Draw(im)
    cx, cy = W / 2, H * 0.47
    far = 0.10                       # size of the far opening relative to the near frame
    def at(f, x, y):                 # f: 0 near .. 1 far; x, y in -1..1 of the near frame
        s = 1 - (1 - far) * f
        return (cx + x * W / 2 * s, cy + y * H * 0.53 * s)
    # floor, ceiling, walls as quads with depth shading
    for i in range(40):
        f0, f1 = i / 40, (i + 1) / 40
        shade = 1 - 0.55 * f0
        wall = tuple(int(c * shade) for c in (196, 178, 96))
        carpet = tuple(int(c * shade) for c in (130, 116, 66))
        ceil = tuple(int(c * shade) for c in (206, 198, 160))
        d.polygon([at(f0, -1, -1), at(f1, -1, -1), at(f1, 1, -1), at(f0, 1, -1)], fill=ceil)
        d.polygon([at(f0, -1, 1), at(f1, -1, 1), at(f1, 1, 1), at(f0, 1, 1)], fill=carpet)
        d.polygon([at(f0, -1, -1), at(f1, -1, -1), at(f1, -1, 1), at(f0, -1, 1)], fill=wall)
        d.polygon([at(f0, 1, -1), at(f1, 1, -1), at(f1, 1, 1), at(f0, 1, 1)], fill=tuple(int(c * 0.9) for c in wall))
    d.rectangle([at(1, -1, -1), at(1, 1, 1)], fill=(60, 54, 30))
    # wallpaper stripes on the left wall
    for k in range(18):
        x = -1 + k * 0.0
    panels = []
    for f, depth in ((0.12, 7.5), (0.38, 15), (0.58, 26), (0.74, 40), (0.86, 58)):
        a, b = at(f, -0.32, -1), at(f + 0.035, 0.32, -1)
        d.rectangle([a[0], a[1] + 2, b[0], b[1] + 2 + 14 * (1 - f)], fill=(255, 252, 238))
        panels.append((((a[0] + b[0]) / 2, a[1] + 8 * (1 - f)), depth))
    im = im.filter(ImageFilter.GaussianBlur(1.2))
    return np.asarray(im).astype(float), panels


# ---------------------------------------------------------------- LensDirt, ported
def halo_tex(S=128):
    y, x = np.mgrid[0:S, 0:S]
    dx, dy = (x + 0.5) / S * 2 - 1, (y + 0.5) / S * 2 - 1
    r = np.sqrt(dx * dx + dy * dy)
    a = np.where(r < 1, 0.3 * np.exp(-r * r * 14) + 0.7 * np.clip(1 - r, 0, 1) ** 1.7, 0)
    return np.clip(a, 0, 1)


def dirt_tex(Wd=384, Hd=216):
    r = random.Random(31337)
    acc = np.zeros((Hd, Wd))
    yy, xx = np.mgrid[0:Hd, 0:Wd]
    def blob(cx, cy, rad, s):
        d = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / rad
        acc[:] += np.where(d < 1, s * (1 - d * d) ** 2, 0)
    for _ in range(34):
        blob(r.uniform(0, Wd), r.uniform(0, Hd), r.uniform(14, 60), r.uniform(0.1, 0.3))
    for _ in range(30):
        blob(r.uniform(0, Wd), r.uniform(0, Hd), r.uniform(1.2, 2.6), r.uniform(0.15, 0.4))
    for _ in range(3):
        x, y = r.uniform(0, Wd), r.uniform(0, Hd)
        ang, ln = r.uniform(0, math.pi * 2), r.uniform(60, 160)
        for s in np.arange(0, ln, 3):
            blob(x + math.cos(ang) * s, y + math.sin(ang) * s + math.sin(s / 30) * 8, 5, 0.06)
    return np.clip(acc, 0, 1)


def over(img, rgb, alpha, x0, y0):
    h, w = alpha.shape
    xs, ys = max(0, x0), max(0, y0)
    xe, ye = min(W, x0 + w), min(H, y0 + h)
    if xe <= xs or ye <= ys:
        return
    a = alpha[ys - y0:ye - y0, xs - x0:xe - x0][..., None]
    img[ys:ye, xs:xe] = img[ys:ye, xs:xe] * (1 - a) + np.array(rgb, float) * a


def lens(img, panels):
    REACH, HALO_PX, HALO_A, DIRT_A = 70, 2600, 0.66, 0.34
    halo = Image.fromarray((halo_tex() * 255).astype(np.uint8))
    best = 0
    # the Studio viewport this was tuned for is ~1920 wide; scale the pixel sizes to this 1280 frame
    k_px = W / 1920
    for (sx, sy), dist in panels:
        score = (1 - dist / REACH) ** 2 * 1.0
        best = max(best, score)
        px = min(max(HALO_PX / dist, 90), 560) * (0.6 + 0.4 * score) * k_px
        a = np.asarray(halo.resize((int(px), int(px * 0.8)), Image.BILINEAR)).astype(float) / 255 * HALO_A * score
        over(img, (255, 244, 214), a, int(sx - px / 2), int(sy - px * 0.4))
    dirt = Image.fromarray((dirt_tex() * 255).astype(np.uint8)).resize((W, H), Image.BILINEAR)
    over(img, (236, 230, 214), np.asarray(dirt).astype(float) / 255 * DIRT_A * best, 0, 0)
    return img


# ---------------------------------------------------------------- TapeTear, ported
def streak_tex(SW=256, SH=24):
    r = random.Random(11)
    rgba = np.zeros((SH, SW, 4))
    for y in range(SH):
        x = 0
        while x < SW:
            run = r.randint(6, 60)
            on = r.random() < 0.6
            v, a = r.randint(170, 255), (r.randint(90, 230) if on else 0)
            rgba[y, x:x + run] = (v, v, v, a)
            x += run
    return rgba


def tear(img):
    st = streak_tex()
    for (y_frac, h, xoff) in ((0.34, 84, -22), (0.61, 40, 14)):
        y0 = int(H * y_frac)
        # shift the picture inside the band sideways -- what the overlay is standing in for, done for
        # real here only to judge it; in game the slip is a dark flat band
        band = img[y0:y0 + h].copy()
        # slip: dark flat band over the lower 55%
        s0 = y0 + int(h * 0.5)
        img[s0:y0 + h] = img[s0:y0 + h] * 0.4 + np.array((10, 10, 9)) * 0.6
        # smear: half the streak texture, stretched over the top 60% of the band
        crop = st[:, rng.randint(0, 128):][:, :128]
        sm = Image.fromarray(crop.astype(np.uint8), "RGBA").resize((int(W * 1.06), int(h * 0.75)), Image.BILINEAR)
        sma = np.asarray(sm).astype(float)
        over(img, (230, 230, 230), sma[..., 3] / 255, xoff - int(W * 0.03), y0)
        # registration fringes
        img[y0:y0 + 3] = img[y0:y0 + 3] * 0.35 + np.array((214, 40, 34)) * 0.65
        img[y0 + h - 3:y0 + h] = img[y0 + h - 3:y0 + h] * 0.4 + np.array((40, 190, 200)) * 0.6
        del band
    # the whole frame drained of colour (Saturation -0.45 * strength 0.8)
    grey = img.mean(axis=2, keepdims=True)
    img = img * (1 - 0.36) + grey * 0.36
    img = (img - 128) * 1.1 + 128
    return img


base, panels = corridor()
a = base.copy()
b = lens(base.copy(), panels)
c = tear(base.copy())
T = ImageFont.truetype("C:/Windows/Fonts/seguisb.ttf", 26)
sheet = Image.new("RGB", (W, (H + 50) * 3), (12, 12, 14))
d = ImageDraw.Draw(sheet)
for i, (img, label) in enumerate(((a, "PLAIN  ·  stand-in corridor, ceiling fluorescents at 7.5 / 15 / 26 / 40 / 58 studs"),
                                   (b, "LENS  ·  halos on the lit panels in front of you, dirt on the glass catching them"),
                                   (c, "TAPE TEAR  ·  a hitch or a nearby chunk arriving, the frame it happens on"))):
    d.text((14, i * (H + 50) + 10), label, font=T, fill=(232, 226, 208))
    sheet.paste(Image.fromarray(np.clip(img, 0, 255).astype(np.uint8)), (0, i * (H + 50) + 50))
sheet.save("test/live/lens_pass.png")
print(sheet.size)
